% Quantify similarity between EEG RSMs obtained from magnitude spectra 
% versus complex spectra and erp
% newborns GA

clear 
close all
clc


%% parameters

par = get_par('experiment', 'newborn'); 

subjects = {'grand-19'};

feat_name_stim = 'ratio';

feat_snr = false; 

roi_name = 'front';         
avg_chans = true; 

harm_selection = [1:6]; 

run_stats = false; 


%%
if feat_snr 
    snr_str = sprintf('%d-%d', par.snr_bins(1), par.snr_bins(2)); 
else
    snr_str = 'none'; 
end

harm_str = vec_to_str(harm_selection, 'format','%d', 'sep','-');

save_path = fullfile(par.deriv_path, 'comparisons', 'mX_X_erp', ...
    sprintf('harm-%s', harm_str), sprintf('snr-%s', snr_str), ...
    sub_num2str(subjects{1}));
mkdir(save_path);


%% load data for X

feat_name_resp = 'X';

subdirs = fullfile(sprintf('response-lf_stim-%s', feat_name_stim), ...
    sprintf('harm-%s', harm_str), ...
    sprintf('snr-%s', snr_str), ...
    sprintf('roi-%s_avgChans-%s', roi_name, jsonencode(avg_chans)), ...
    sub_num2str(subjects{1}));

fname = fullfile(par.results_path, subdirs, ...
    sprintf('%s_feat-%s_method-pearson_nCateg-2-3-4-5_perm.mat', ...
    sub_num2str(subjects{1}), ...
    feat_name_resp));

res_X.res = load(fname);

fname = fullfile(par.results_path, subdirs, ...
    sprintf('%s_feat-%s_method-pearson_rdm.mat', ...
    sub_num2str(subjects{1}), ...
    feat_name_resp));

res_X.rdm = load(fname);



%% load data for mX

feat_name_resp = 'mX';

subdirs = fullfile(sprintf('response-lf_stim-%s', feat_name_stim), ...
    sprintf('harm-%s', harm_str), ...
    sprintf('snr-%s', snr_str), ...
    sprintf('roi-%s_avgChans-%s', roi_name, jsonencode(avg_chans)), ...
    sub_num2str(subjects{1}));

fname = fullfile(par.results_path, subdirs, ...
    sprintf('%s_feat-%s_method-pearson_nCateg-2-3-4-5_perm.mat', ...
    sub_num2str(subjects{1}), ...
    feat_name_resp));

res_mX.res = load(fname);

fname = fullfile(par.results_path, subdirs, ...
    sprintf('%s_feat-%s_method-pearson_rdm.mat', ...
    sub_num2str(subjects{1}), ...
    feat_name_resp));

res_mX.rdm = load(fname);


%% load data for erp

feat_name_resp = 'erp';

subdirs = fullfile(sprintf('response-erp_stim-%s', feat_name_stim), ...
    'lfp-10Hz', ...
    sprintf('roi-%s_avgChans-%s', roi_name, jsonencode(avg_chans)), ...
    sub_num2str(subjects{1}));

fname = fullfile(par.results_path, subdirs, ...
    sprintf('%s_feat-%s_method-pearson_nCateg-2-3-4-5_perm.mat', ...
    sub_num2str(subjects{1}), ...
    feat_name_resp));

res_erp.res = load(fname);

fname = fullfile(par.results_path, subdirs, ...
    sprintf('%s_feat-%s_method-pearson_rdm.mat', ...
    sub_num2str(subjects{1}), ...
    feat_name_resp));

res_erp.rdm = load(fname);


%% load stimulus
load(fullfile(par.deriv_path, 'stimuli', 'stim.mat'));
rdm_stim = rsa_stim_lf(par, [], 'feat', feat_name_stim);


%% correlate RDMs based on X and mX

% save fname
fname_save_base = fullfile(save_path, ...
    sprintf('response-lf_featStim-%s_harm-%s_snr-%s_roi-%s_avgChans-%s_feat-mX-vs-X', ...
    feat_name_stim, ...
    harm_str, ...
    snr_str, ...
    roi_name, ...
    jsonencode(avg_chans) ));


if exist([fname_save_base, '_permInd.mat']) && ~run_stats
    clear res_ind_mX_vs_X
    load([fname_save_base, '_permInd.mat']);
else
    res_ind_mX_vs_X = [];

    [res_ind_mX_vs_X.r_obs, res_ind_mX_vs_X.p_perm, res_ind_mX_vs_X.r_null_dist] = ...
        perm_rdm_corr(...
        res_mX.rdm.rdm, ...
        res_X.rdm.rdm, ...
        10000, ...
        'parfor', true, ...
        'covariate', rdm_stim);

    save([fname_save_base, '_permInd.mat'], 'res_ind_mX_vs_X');
end


%% correlate RDMs based on erp and mX

% save fname
fname_save_base = fullfile(save_path, ...
    sprintf('response-lf_featStim-%s_harm-%s_snr-%s_roi-%s_avgChans-%s_feat-mX-vs-erp', ...
    feat_name_stim, ...
    harm_str, ...
    snr_str, ...
    roi_name, ...
    jsonencode(avg_chans) ...
    ));


if exist([fname_save_base, '_permInd.mat']) && ~run_stats
    clear res_ind_mX_vs_erp
    load([fname_save_base, '_permInd.mat']);
else
    res_ind_mX_vs_erp = [];

    [res_ind_mX_vs_erp.r_obs, res_ind_mX_vs_erp.p_perm, res_ind_mX_vs_erp.r_null_dist] = ...
        perm_rdm_corr(...
        res_mX.rdm.rdm, ...
        res_erp.rdm.rdm, ...
        10000, ...
        'parfor', true, ...
        'covariate', rdm_stim);

    save([fname_save_base, '_permInd.mat'], 'res_ind_mX_vs_erp');
end